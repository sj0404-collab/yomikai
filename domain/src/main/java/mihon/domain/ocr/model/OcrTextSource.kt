package mihon.domain.ocr.model

/**
 * Кто распознал текст — для показа читателю.
 *
 * Существует из-за тихого фолбэка: без сети онлайн-движок не отвечает, и
 * страницу читает локальный. Читатель, не видящий этого, сравнивает
 * качество двух разных движков и делает вывод, что «онлайн читает так же,
 * как локальный». [usedInsteadOfSelected] говорит, что подмена произошла,
 * чтобы вывод был честным.
 */
data class OcrTextSource(
    /** Движок, который вернул текст на самом деле. */
    val engine: OcrModel,
    /** Текст прочитан не тем движком, который выбран в настройках. */
    val usedInsteadOfSelected: Boolean,
)
