package mihon.data.ocr

/**
 * Режим чтения, который соответствует пресету типа контента.
 *
 * Порядок распознавания ([OcrTuning.readingOrder]) и направление листания
 * страниц — это одна и та же сущность, описанная в двух местах: OCR режет
 * страницу по порядку чтения, а вьюер листает её в том же направлении. Если их
 * развести, «манхва» распознаётся вертикальными полосами, но листается
 * постранично справа налево, и текст собирается в кашу.
 *
 * Подсказка декларативная и живёт в `data`-модули, поэтому её можно проверить
 * unit-тестом на JVM. Конкретный вьюер (`ReadingMode`) относится к app-модули и
 * сопоставляется там же — здесь только намерение.
 */
enum class OcrViewerHint(
    val id: String,
    /** Человекочитаемое название для отчётов и подсказок в настройках. */
    val title: String,
) {
    /** Пресет не предписывает вьюер: выбор пользователя не трогаем. */
    KEEP("keep", "без изменений"),

    /** Постранично справа налево — японская манга. */
    PAGER_RTL("pager_rtl", "постранично справа налево"),

    /** Постранично слева направо — западный комикс. */
    PAGER_LTR("pager_ltr", "постранично слева направо"),

    /** Вертикальная лента — манхва и вебтуны. */
    WEBTOON("webtoon", "вертикальная лента (вебтун)"),
    ;

    companion object {
        fun fromId(id: String?): OcrViewerHint =
            entries.firstOrNull { it.id == id?.trim()?.lowercase() } ?: KEEP

        /**
         * Порядок чтения OCR → подсказка вьюера. Единственное место, где два
         * представления связаны, поэтому тест сверяет их друг с другом.
         */
        fun forReadingOrder(readingOrder: String): OcrViewerHint = when (readingOrder) {
            "rtl" -> PAGER_RTL
            "ltr" -> PAGER_LTR
            "vertical" -> WEBTOON
            else -> KEEP
        }
    }
}
