     * на 500 000 случайных строк), а здесь их ноль на том же объёме.
     */
    private val upperTable: LongArray = buildUpperTable()

    /** Есть ли словоформа (любого регистра) во встроенном словаре. */
    fun containsUpper(word: String): Boolean {
        if (word.isEmpty()) return false
        var hash = hashUpper(word)
        // Ноль в таблице означает «пусто», поэтому он непригоден как значение.
        if (hash == 0L) hash = 1L
        val table = upperTable
        val mask = table.size - 1
        var i = slot(table, hash)
        while (true) {
            val stored = table[i]
            if (stored == 0L) return false
            if (stored == hash) return true
            i = (i + 1) and mask
        }
    }

    /**
     * Заполнено при нагрузке 3 014 492 / 8 388 608 ≈ 0.36, то есть прозондировка
     * почти всегда упирается в первую же свободную ячейку.
     */
    private fun buildUpperTable(): LongArray {
        var capacity = 1 shl 23
        var table = LongArray(capacity)
        var size = 0
        for (factory in partFactories) {
            for (word in factory()) {
                var hash = hashUpper(word)
                if (hash == 0L) hash = 1L
                if (size * 2 >= capacity) {
                    val grown = LongArray(capacity * 2)
                    for (stored in table) {
                        if (stored == 0L) continue
                        var g = slot(grown, stored)
                        while (grown[g] != 0L) g = (g + 1) and (grown.size - 1)
                        grown[g] = stored
                    }
                    table = grown
                    capacity *= 2
                }
                var i = slot(table, hash)
                while (table[i] != 0L) i = (i + 1) and (capacity - 1)
                table[i] = hash
                size++
            }
        }
        return table
    }

    private fun slot(table: LongArray, hash: Long): Int =
        (hash xor (hash ushr 32)).toInt() and (table.size - 1)

    /** FNV-1a 64 по uppercase-символам, без создания строки-копии. */
    private fun hashUpper(word: String): Long {
        var hash = -3750763034362895579L
        for (ch in word) {
            hash = (hash xor ch.uppercaseChar().code.toLong()) * 1099511628211L
        }
        return hash
    }
