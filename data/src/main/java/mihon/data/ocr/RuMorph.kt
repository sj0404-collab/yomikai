package mihon.data.ocr

/**
 * Лёгкая офлайн-морфология: пол говорящего по окончаниям словоформ.
 *
 * Нужна для интонаций локальных голосов: когда словарные маркеры
 * («сестра», «господин») в реплике отсутствуют, AutoReadEngine выбирает
 * голос по перевесу родовых окончаний. Никакой подмены текста: только
 * классификация. Лемматизация и части речи — отдельный воркстрим.
 */
object RuMorph {

    /** Слова женского рода с «мужскими» признаками и наоборот. */
    private val MASC_EXCEPTIONS = setOf(
        "папа", "дядя", "мужчина", "юноша", "староста", "судья",
        "старшина", "воевода", "юнга", "молодца", "сирота", "коллега",
    )

    private val FEM_EXCEPTIONS = setOf(
        "моль", "соль", "боль", "роль", "фасоль", "метель", "постель",
        "неделя", "свадьба", "смерть", "дверь", "тень", "осень", "лошадь",
    )

    private val CONSONANTS = "бвгджзклмнпрстфхцчшщ"

    /**
     * «female» / «male» / null: перевес родовых окончаний >= 2 слов,
     * иначе нейтрально (лучше никакой пол, чем ошибочный).
     */
    fun guessGender(text: String): String? {
        var fem = 0
        var masc = 0
        for (m in Regex("[а-яёА-ЯЁ]{4,}").findAll(text)) {
            val w = m.value.lowercase()
            when {
                w in MASC_EXCEPTIONS -> masc++
                w in FEM_EXCEPTIONS -> fem++
                w.endsWith("ость") || w.endsWith("ия") || w.endsWith("ия") -> fem++
                w.endsWith("а") || w.endsWith("я") -> fem++
                w.endsWith("й") || w.endsWith("ец") || w.last() in CONSONANTS -> masc++
            }
        }
        return when {
            fem - masc >= 2 -> "female"
            masc - fem >= 2 -> "male"
            else -> null
        }
    }

    /**
     * Служебные части речи и местоимения (закрытые классы). В OCR-плашке
     * такие слова красятся другим цветом, чем знаменательные «реплики»
     * (существительные/глаголы/прилагательные) — см. ReaderOcrOverlayRenderer.
     */
    private val FUNCTION_WORDS = setOf(
        // предлоги
        "в", "во", "на", "за", "из", "к", "ко", "по", "с", "со", "у", "о", "об",
        "обо", "от", "ото", "до", "для", "без", "безо", "при", "про", "над",
        "под", "подо", "перед", "передо", "между", "через", "около", "возле",
        "после", "кроме", "вместо", "внутри", "вне", "среди", "против", "ради",
        "благодаря", "согласно", "вопреки", "вдоль", "поперёк", "насчёт",
        "из-за", "из-под",
        // союзы
        "и", "а", "но", "да", "или", "либо", "чтобы", "как", "когда", "если",
        "хотя", "пока", "потому", "поэтому", "зато", "причём", "притом", "коль",
        "чем", "нежели", "тоже", "также",
        // частицы
        "не", "ни", "же", "бы", "ли", "вот", "вон", "ведь", "только", "лишь",
        "даже", "именно", "уж", "ещё", "разве", "неужели", "ну", "аж",
        // местоимения
        "я", "ты", "он", "она", "оно", "мы", "вы", "они", "меня", "тебя", "его",
        "её", "нас", "вас", "их", "мне", "тебе", "ему", "ей", "нам", "вам", "им",
        "мной", "мною", "тобой", "тобою", "нами", "вами", "ими", "себя", "себе",
        "собой", "весь", "всё", "вся", "все", "этот", "эта", "это", "эти", "тот",
        "та", "то", "те", "такой", "такая", "такое", "такие", "мой", "моя", "моё",
        "мои", "твой", "твоя", "твоё", "твои", "наш", "наша", "наше", "наши",
        "ваш", "ваша", "ваше", "ваши", "свой", "своя", "своё", "свои", "кто",
        "что", "кого", "чего", "кому", "чему", "кем", "ком", "какой", "какая",
        "какое", "какие", "чей", "чья", "чьё", "чьи", "который", "которая",
        "которое", "которые", "сколько", "никто", "ничто", "некто", "нечто",
        "некоторый", "любой", "каждый", "сам", "сама", "само", "сами", "самый",
        "другой", "другая", "другое", "другие", "иной", "иная", "иное", "иные",
    )

    /**
     * Знаменательное ли слово: true для предлогов, союзов, частиц и
     * местоимений. Не-кириллические слова и пустые строки — знаменательные
     * (красятся как обычная реплика).
     */
    fun isFunctionWord(word: String): Boolean {
        val w = word.lowercase().trim { !it.isLetter() }
        return w.isNotEmpty() && w in FUNCTION_WORDS
    }


    /** Часть речи грубо по окончанию: для будущей лемматизации/отладки. */
    fun guessPos(word: String): String {
        val w = word.lowercase()
        return when {
            w.endsWith("ть") || w.endsWith("л") || w.endsWith("ла") ||
                w.endsWith("ли") || w.endsWith("ю") || w.endsWith("ет") ||
                w.endsWith("ут") || w.endsWith("ат") || w.endsWith("ят") -> "verb"
            w.endsWith("ый") || w.endsWith("ий") || w.endsWith("ой") ||
                w.endsWith("ая") || w.endsWith("яя") || w.endsWith("ое") ||
                w.endsWith("ее") -> "adj"
            else -> "noun"
        }
    }
}
