package eu.kanade.tachiyomi.data.tts

/**
 * Самодельный ВСТРОЕННЫЙ AI-помощник озвучки. Никаких API-ключей и сети:
 * пол говорящего определяется лингвистической эвристикой прямо на устройстве.
 *
 * Для русского текста работает морфология:
 *  • глаголы прошедшего времени от первого лица: «сказала/подумала/пришла…»
 *    → женская реплика; «сказал/подумал/пришёл…» → мужская;
 *  • самоописания: «я рада», «я сама», «я готова» vs «я рад», «я сам»,
 *    «я готов»;
 *  • обращения-маркеры: «сестрёнка, ты…», «братик, ты…» относятся к
 *    собеседнику и НЕ учитываются для говорящего.
 *
 * Скоринг: считаем женские и мужские маркеры, отвечаем полом только при
 * явном перевесе — иначе null (нейтральный голос). Лучше промолчать, чем
 * озвучить неверным полом.
 */
object LocalSpeakerAi {

    // «я/мне/меня …-ла» — окончание прошедшего времени ж.р.
    private val feminineVerb = Regex("""(?:^|\s)(?:я|ведь я|и я)\s+(?:\S+\s+){0,2}?\S+ла(?:сь)?\b""")
    private val masculineVerb = Regex("""(?:^|\s)(?:я|ведь я|и я)\s+(?:\S+\s+){0,2}?\S+(?:[^аеиоуыэюяль]|ёл|ел|ал|ул|ил|ыл|л)(?:ся)?\b""")

    private val feminineSelf = listOf(
        "я сама", "я рада", "я готова", "я должна", "я уверена", "я согласна",
        "я не могла", "я была", "я хотела", "я думала", "я поняла", "я знала",
        "я видела", "я слышала", "я пришла", "я решила", "сама справлюсь",
        "я устала", "я испугалась", "я замужем",
        // самоидентификация через существительные
        "я мама", "я мать", "я сестра", "я дочь", "я бабушка", "я девушка",
        "я женщина", "я принцесса", "я королева", "я ведьма", "я учительница",
        // самоидентификация через прилагательные
        "я красивая", "я сильная", "я умная", "я добрая", "я злая",
        "я беременна", "я влюблена", "я свободна", "я занята", "я права",
    )
    private val masculineSelf = listOf(
        "я сам", "я рад", "я готов", "я должен", "я уверен", "я согласен",
        "я не мог", "я был", "я хотел", "я думал", "я понял", "я знал",
        "я видел", "я слышал", "я пришёл", "я пришел", "я решил", "сам справлюсь",
        "я устал", "я испугался", "я женат",
        // самоидентификация через существительные
        "я папа", "я отец", "я брат", "я сын", "я дед", "я мужчина", "я парень",
        "я юноша", "я принц", "я король", "я воин", "я рыцарь", "я маг",
        // самоидентификация через прилагательные
        "я красивый", "я сильный", "я умный", "я добрый", "я злой",
        "я свободен", "я занят", "я прав", "я виноват",
    )

    /** Пол говорящего: "female" | "male" | null (не уверены). */
    fun guessGender(rawText: String): String? {
        val text = " " + rawText.lowercase().replace('ё', 'ё') + " "

        var female = 0
        var male = 0

        for (marker in feminineSelf) if (text.contains(marker)) female += 2
        for (marker in masculineSelf) if (text.contains(marker)) male += 2

        if (feminineVerb.containsMatchIn(text)) female += 1
        else if (masculineVerb.containsMatchIn(text)) male += 1

        return when {
            female > male -> "female"
            male > female -> "male"
            else -> null
        }
    }

    /**
     * Пол для каждой реплики кадра. Реплики без явных маркеров наследуют
     * пол предыдущей уверенной реплики того же кадра только если стоят
     * вплотную (диалог одного персонажа из нескольких бабблов подряд).
     */
    fun guessGenders(lines: List<String>): List<String?> {
        val result = arrayOfNulls<String>(lines.size)
        for (i in lines.indices) {
            result[i] = guessGender(lines[i])
        }
        return result.toList()
    }
}
