package eu.kanade.tachiyomi.data.ai

/**
 * Как ассистент работает с ЭТОЙ книгой: три настройки, которые читатель
 * переключает прямо в чате читалки.
 *
 *  * [MODE_CHAT] — обычный помощник: отвечает по книге, ищет источники, ведёт
 *    дела. То, что было по умолчанию.
 *  * [MODE_ROLEPLAY] — «дружеская встреча»: ассистент отыгрывает героев и
 *    общается вместо справочного тона. Знания книги при этом не теряются —
 *    режим меняет тон, а не память.
 *  * [MATURE_ALLOWED] — для книг 18+ ассистент может обсуждать зрелые темы.
 *    Для остальных книг запрет остаётся жёстким.
 *  * [CENSORSHIP_ON] — фильтр грубых слов в ответе. Это косметика для
 *    спокойного чтения, а не фильтр содержания: грубые слова маскируются
 *    звёздочками, смысл ответа не меняется.
 *
 * Жёсткая граница, которую нельзя переключить: никакого сексуального
 * контента с несовершеннолетними, никаких отыгрышей реальных людей и
 * никакого сексуального насилия. Это не настройка, а правило ассистента.
 */
object BookChatProfile {

    const val MODE_CHAT = "chat"
    const val MODE_ROLEPLAY = "roleplay"

    const val MODE_CHAT_TITLE = "Чат"
    const val MODE_ROLEPLAY_TITLE = "Отыгрыш"

    val MODES = listOf(MODE_CHAT, MODE_ROLEPLAY)

    /** Настройки книги в одном месте: их читает и UI, и промпт. */
    data class Settings(
        val mode: String = MODE_CHAT,
        val matureAllowed: Boolean = false,
        val censorship: Boolean = true,
        val title: String = "",
        /** Какое издание/перевод читать — выясняет агент поиском. */
        val edition: String = "",
    )

    fun modeTitle(mode: String): String = when (mode) {
        MODE_ROLEPLAY -> MODE_ROLEPLAY_TITLE
        else -> MODE_CHAT_TITLE
    }

    /**
     * Слова, которые маскируются в режиме цензуры. Список короткий и
     * намеренно без «серьёзного» содержания: он не должен ломать перевод
     * реплик, а только смягчать грубую лексику.
     */
    val CENSOR_WORDS: List<String> = listOf(
        "блядь", "ебан", "ебать", "ебану", "хуй", "хуе", "хуя", "пизд", "мудак",
        "сука", "гандон", "дрочи", "залуп",
    )

    /**
     * Маскирует грубую лексику, сохраняя длину слова. Первая буква остаётся,
     * остальное — звёздочки: так видно, что слово было, но текст можно читать
     * вслух.
     *
     * Флаг `u` обязателен: без него `(?i)` в Java не сворачивает регистр
     * кириллицы, и «БЛЯДЬ» проходило бы мимо фильтра (проверено на JVM).
     */
    fun maskCensored(text: String, words: List<String> = CENSOR_WORDS): String {
        if (text.isEmpty() || words.isEmpty()) return text
        return censorPattern(words).replace(text) { match ->
            val word = match.value
            if (word.length <= 2) "*".repeat(word.length) else word.take(1) + "*".repeat(word.length - 1)
        }
    }

    /** Есть ли в тексте то, что нужно замаскировать (регистр кириллицы учитывается). */
    fun hasCensoredWords(text: String, words: List<String> = CENSOR_WORDS): Boolean =
        text.isNotEmpty() && censorPattern(words).containsMatchIn(text)

    private fun censorPattern(words: List<String>): Regex =
        Regex("(?iu)" + words.joinToString("|") { Regex.escape(it) })

    /**
     * Блок ограничений для промпта. Возвращает жёсткие рамки: что можно,
     * что нельзя, и в каком тоне говорить. Книжные настройки выбирает
     * читатель, поэтому модель не решает за него.
     */
    fun render(
        mode: String,
        matureAllowed: Boolean,
        censorship: Boolean,
        bookTitle: String = "",
    ): String {
        val title = bookTitle.ifBlank { "книга" }
        return buildString {
            append("РЕЖИМ РАБОТЫ С КНИГОЙ (выбрал пользователь, не обсуждается):")
            if (mode == MODE_ROLEPLAY) {
                append("\n- Тон: ты отыгрываешь персонажей «$title» и общаешься с читателем ")
                append("как собеседник в дружеской встрече: можно шутить, спорить, флиртовать ")
                append("в рамках характера героя.")
                append("\n- Знания книги при этом не теряются: сюжет, порядок чтения, ")
                append("имена и термины — как обычно, из блока знаний выше.")
                // Ремарки в скобках — не служебная разметка, а то, что
                // озвучка умеет произносить. Без этого указания модель пишет
                // прямую речь, и вздохи/крики в озвучке просто не появятся.
                append("\n- Реплику можно начать с ремарки в круглых скобках, ")
                append("она будет произнесена голосом, а не прочитана как слово: ")
                append("(вздох) (вдох) (стон) (крик) (крик помощи) (смеётся) (кашель). ")
                append("Состояние героя тоже можно указать: (шёпотом) (бегом) ")
                append("(устал) (слабость) (боль) (боюсь) (злюсь) (удивлён) — ")
                append("оно меняет тон и темп всей реплики.")
                append("\n- Междометия пиши буквами, они распознаются по длине: ")
                append("«а» — удивление, «аа» — попытка закричать, «ааа» — крик, ")
                append("«ах» — вдох или испуг.")
                append("\n- Прочей разметки не нужно: никаких тегов, списков и ")
                append("служебных пояснений, только речь и эти ремарки.")
            } else {
                append("\n- Тон: деловой помощник чтения. Коротко, по существу, без ")
                append("отыгрыша и без обращения к читателю по имени.")
            }
            if (matureAllowed) {
                append("\n- Книга помечена 18+: можешь называть зрелые темы и обсуждать их ")
                append("в рамках сюжета, без домысливания откровенных сцен.")
            } else {
                append("\n- Книга не помечена 18+: зрелые темы и постельные сцены не ")
                append("описывай и не развивай, даже если спросят прямо.")
            }
            append("\n- Запрещено всегда: сексуальный контент с несовершеннолетними, ")
            append("сексуальное насилие, отыгрыш реальных людей. Это не обсуждается ")
            append("и не отменяется настройками.")
            if (censorship) {
                append("\n- Включён фильтр грубых слов: не пиши их в ответе.")
            }
        }
    }
}
