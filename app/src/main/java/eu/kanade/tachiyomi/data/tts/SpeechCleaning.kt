package eu.kanade.tachiyomi.data.tts

/**
 * Подготовка текста реплики к синтезу речи.
 *
 * Повторяет `cleanSpeech` из KOMA-читалки дословно: движок одно и то же
 * правило должно применять в обеих читалках, иначе одна читает «высочество»,
 * а другая — «высо-чество».
 *
 * Зачем это нужно. OCR отдаёт текст с переносами: слово, разорванное концом
 * строки, приходит как «высо-» + «чество», а иногда и с разряженными буквами —
 * «в д а - ль». Синтезатор читает дефис как паузу и произносит обрывки по
 * слогам: «вы - сочест - ва», «в д а - ль».
 */
object SpeechCleaning {

    /**
     * Убирает переносы и склеивает разорванные слова.
     *
     * Дефис между буквами удаляется вместе с пробелами вокруг, цепочки
     * одиночных букв («в д а л ь») склеиваются в слово.
     */
    fun clean(raw: String): String {
        var text = raw
            .replace(Regex("(?<=\\p{L})\\s*-\\s*(?=\\p{L})"), "")
            .replace(Regex("\\s+"), " ")
            .trim()
        // Склеиваем цепочки одиночных букв: «в д а ль» → «вдаль».
        repeat(3) {
            text = text.replace(Regex("(?<!\\p{L})\\p{L}(\\s+\\p{L}){1,4}(?!\\p{L})")) { match ->
                match.value.replace(" ", "")
            }
        }
        return text.trim()
    }
}
