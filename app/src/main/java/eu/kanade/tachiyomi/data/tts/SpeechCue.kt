package eu.kanade.tachiyomi.data.tts

/**
 * Театральные ремарки и междометия: что произнести и как.
 *
 * Проблема была в трёх местах. Первое: ремарка в скобках попадала в синтез
 * либо выбрасывалась совсем, либо читалась словом — «(вздох)» звучало как
 * «вздох». Второе: `а`, `аа`, `ааа` не различались, хотя означают разное —
 * удивление, попытку закричать, крик. Третье: состояние персонажа (бежит,
 * устал, обессилел, зовёт помощь) вообще не влияло на голос.
 *
 * Ремарки делятся на два вида, и это не украшение, а смысл:
 *
 *  * **звук** (вздох, вдох, стон, крик, смех, кашель) — ПРОИЗНОСИТСЯ.
 *    Синтезатор не умеет вздыхать, поэтому звук передаётся вытянутым
 *    «А-а-а», а характер звука берёт на себя питч и темп;
 *  * **состояние** (шёпот, бег, усталость, слабость, боль, испуг, злость) —
 *    НЕ произносится, а меняет подачу всей реплики. Произносить слово
 *    «шёпот» вслух нельзя, это сломало бы чтение.
 *
 * Ничего не теряется: неизвестная ремарка просто снимается, но любой звук из
 * таблицы произносится, а любое состояние доходит до голоса модификатором.
 *
 * Модуль чистый — без Android и без движка, поэтому проверяется на JVM.
 */
object SpeechCue {

    /** Как произнести один кусок реплики. */
    data class Delivery(
        val text: String,
        val pitch: Float = 1.0f,
        val rate: Float = 1.0f,
        val pauseAfterMs: Int = 0,
        /**
         * Кусок пришёл из звука или междометия, то есть его подача уже
         * задана здесь. Движок в этом случае не добавляет поверх знаковую
         * пунктуацию, иначе «Ааа!» получил бы крик дважды.
         */
        val fromCue: Boolean = false,
        /**
         * Кусок — настоящий звук (вздох, стон, крик), который обычный голос
         * не умеет произносить, а лишь читает буквами. Такие куски — ровно те,
         * что мост отправляет в плагин озвучки; междометия и обычный текст
         * остаются на голосе.
         */
        val isSound: Boolean = false,
        /**
         * Тип звука («sigh», «moan», «cry», …). Плагину нужен именно тип: он
         * подбирает нужный образец, а не читает подставленный текст.
         */
        val soundId: String? = null,
    )

