    /**
     * Ремарки в скобках: `(вздох)`, `[ааа]`, `*шёпотом*`, а также курсив и
     * кавычки. Закрывающая скобка экранирована — без экрана ICU-движок
     * части Android падает прямо на разборе шаблона (см. предупреждение
     * в [SpeechMarkup]).
     */
    // Внутренняя часть ремарки допускает `*`: разметка `(*шёпотом*)` и `(шёпотом)`
    // должны разбираться одинаково. Запрещены только закрывающие скобки — иначе
    // группа «съест» конец ремарки. Закрывающая часть — целая серия: у `(*шёпотом*)`
    // их две (`*` и `)`), иначе хвост утекал бы в произносимый текст.
    private val CUE_SPAN = Regex("""[(\[*]\s*([^()\[\]\{\}]{1,60}?)\s*[\)\]\*]+""")

    /**
     * Кандидат в междометие: короткая «слово-сгусток» из букв и дефисов,
     * стоящая сама по себе. Дальше решает белый список, а не сам шаблон.
     *
     * Так сделано намеренно. Если разрешить «любую последовательность из
     * а, у, о, м, х», под неё попадут обычные слова: «еху», «уху», «аму»,
     * «уа», «хам», «ом». Список явный, поэтому «хам» останется словом.
     */
    private val CANDIDATE = Regex("""(?<![\p{L}\p{N}])([\p{L}\-]{1,12})(?![\p{L}\p{N}])""")

    /**
     * Белый список междометий. Повторы букв и дефисы значимы: «а» — это
     * удивление, «аа» — попытка закричать, «ааа» — уже крик, «а-а-а» —
     * то же, но тянутое.
     */
    private val INTERJECTIONS: Set<String> = setOf(
        // удивление, короткое «а» и его вытянутые варианты
        "а", "аа", "ааа", "аааа", "ааааа", "аааааа",
        "а-а", "а-а-а", "а-а-а-а", "а-а-а-а-а",
        "а-а-а-а-а", "а-ах", "а-а-а-х", "аа-а", "а-а-ах", "аах", "а-у-а",
        // вдох / выдох / хрип
        "ах", "аха", "ахх", "ааах", "ааа-а", "ух", "уха", "уух", "уах", "ухх",
        "ох", "оха", "о-о", "о-о-о", "оах", "охх",
        // тяжёлое дыхание, усталость
        "у", "уу", "у-у", "у-у-у", "у-у-у-у", "ы", "ыы", "ыыы", "ыыыы", "ы-ы",
        // мысль, размышление
        "мм", "ммм", "м-м", "м-м-м", "мммм", "ммммм", "хм", "х-м", "хмм", "хммм",
        "эм", "эмм", "э-э", "э-э-э", "эге-гей", "и-и", "х-х",
        // согласие и понимание
        "угу", "угу-угу", "ага", "ага-ага", "ого", "ой", "уау", "а-у", "уа-у", "а-и",
        // просьба тишины и раздражение
        "ти", "тсс", "тш", "шш", "пф", "пфф", "пфс",
        // резкий испуг
        "бам", "бум", "бух", "бах", "ай", "аааа", "ой-ой",
    )

    /** Знаки, которые приклеиваются к междометию и не должны отделяться. */
    private val TAIL_PUNCT = "!?.,…"

    /** Что за звук задан ремаркой, или null. */
    fun soundOf(remark: String): Sound? {
        val low = remark.lowercase()
        return SOUNDS.firstOrNull { s -> s.words.any { low.contains(it) } }
    }

    /** Какое состояние описано в ремарке, или null. */
    fun stateOf(remark: String): State? {
        val low = remark.lowercase()
        return STATES.firstOrNull { s -> s.words.any { low.contains(it) } }
    }

    /**
     * Является ли токен междометием.
     *
     * Хвостовая пунктуация не мешает: «Ааа!», «ах…» — это то же самое
     * междометие, просто с восклицательным знаком. Без этого `*Ааа!*` и `[Ааа!]`
     * молчали: в наборе лежит «Ааа», а проверяли мы «Ааа!».
     */
    fun isInterjection(token: String): Boolean =
        token.lowercase().trimEnd(' ', '!', '?', '.', ',', ';', ':', '…', '‼', '⁇') in INTERJECTIONS

    /**
     * Подставляет вместо ремарок произносимое: звук → вытянутое междометие,
     * состояние и неизвестная ремарка → пусто (состояние меняет подачу, а не
     * текст; неизвестное не читается словом). Голое междометие в скобках
     * остаётся: `[ааа]` — это и есть звук, терять его незачем.
     */
    fun render(text: String): String {
        var out = CUE_SPAN.replace(text) { match ->
            val remark = match.groupValues[1].trim('*').trim()
            soundOf(remark)?.spoken
                ?: if (isInterjection(remark)) remark
                // `*курсив*` — текст, который нужно показать и прочесть, а не
                // указание говорящему. Согласуется с deliveries().
                else if (match.value.trimStart().startsWith("*") && stateOf(remark) == null) {
                    remark.replace(Regex("[*~]"), " ")
                } else ""
        }
        out = out.replace(Regex("[*~]"), " ")
        out = out.replace(Regex(""" {2,}"""), " ")
        return out.replace(Regex("""\s+([,.!?;:…])"""), "$1").trim()
    }

    /** Слова согласия и понимания — ровный тон, без испуга. */
    // «уа» убрано намеренно: это сленговое «назад», а не междометие.
    private val AGREEMENT = setOf("ага", "ага-ага", "угу", "угу-угу", "ого", "уау", "а-у", "а-у-а")

    /** Звуки размышления — тише и медленнее, реплика «потом». */
    private val THINKING = setOf(
        "мм", "ммм", "мммм", "ммммм", "м-м", "м-м-м", "хм", "х-м", "хмм", "хммм",
        "х-х", "эм", "эмм", "э-э", "э-э-э", "эге-гей", "и-и", "у", "уу", "у-у", "у-у-у",
        "у-у-у-у", "ы", "ыы", "ыыы", "ыыыы", "ы-ы", "ти", "тш", "шш",
    )

    /** Резкий испуг — короткий и высокий. */
    private val STARTLE = setOf("ой", "ой-ой", "ай", "бам", "бум", "бух", "бах")

    /**
     * Подача междометия по его виду и длине. Одно «а» — удивление, «аа» —
     * попытка закричать, «ааа» и длиннее — крик; раньше они читались
     * одинаково, и разница терялась.
     */
    fun interjectionDelivery(word: String): Delivery {
        // Синтезу регистр безразличен, но единый вид удобнее в логах и в
        // разметке: `ааа` из ремарки и в начале фразы выглядит одинаково.
        val spoken = word.replaceFirstChar { it.uppercaseChar() }
        val core = spoken.trim().lowercase().trim(*TAIL_PUNCT.toCharArray())
        val letters = core.filter { it.isLetter() }
        val aCount = letters.count { it == 'а' || it == 'a' }
        val breath = core.any { it == 'х' || it == 'ц' || it == 'h' }
        val sigh = core.any { it == 'у' || it == 'о' || it == 'ы' || it == 'y' }
        val long = letters.length >= 4
        val (p, r, pause) = when {
            core in AGREEMENT -> Triple(1.04f, 0.98f, 200)
            core in THINKING -> Triple(0.96f, 0.86f, 240)
            core in STARTLE -> Triple(1.18f, 1.06f, 220)
            breath -> Triple(1.06f, 0.92f, 240)
            sigh -> Triple(0.88f, 0.84f, 260)
            aCount >= 3 || long -> Triple(1.28f, 1.12f, 320)
            aCount == 2 -> Triple(1.16f, 0.90f, 240)
            else -> Triple(1.10f, 0.95f, 180)
        }
        return Delivery(spoken, pitch = p, rate = r, pauseAfterMs = pause, fromCue = true)
    }

    /**
     * Полная разметка реплики: куски со своей подачей.
     *
     * Ремарки убираются (звук превращается в произносимое с собственным
     * голосом), состояние становится множителем подачи, а голые междометия
     * выделяются отдельными кусками. Именно так «ааа» перестаёт читаться
     * вместе со следующей фразой общим тоном, а шёпот делает тише и
     * медленнее всю реплику.
     */
    fun deliveries(sentence: String): List<Delivery> {
        if (sentence.isBlank()) return emptyList()

        val spans = CUE_SPAN.findAll(sentence).toList()

        // Состояние: при нескольких ремарках побеждает самое заметное
        // (самая крайняя скорость), чтобы «(устал) (бегом)» не усреднялось.
        val state = spans.mapNotNull { stateOf(it.groupValues[1]) }
            .maxByOrNull { kotlin.math.abs(it.rate - 1f) }
        val sp = state?.pitch ?: 1.0f
        val sr = state?.rate ?: 1.0f

        val out = mutableListOf<Delivery>()

        /** Раскладывает обычный текст: голые междометия — отдельными кусками. */
        fun plain(raw: String) {
            // Осиротевшие `*` и `~` от незакрытой разметки не произносятся
            // и не превращаются в отдельный вызов движка.
            val part = raw.replace(Regex("[*~]"), " ")
            var last = 0
            CANDIDATE.findAll(part).forEach { m ->
                if (!isInterjection(m.value)) return@forEach
                // Знаки после междометия («А-а-а!») остаются с ним же, иначе
                // восклицательный знак уедет в отдельный кусок.
                var end = m.range.last + 1
                while (end < part.length && part[end] in TAIL_PUNCT) end++
                val head = part.substring(last, m.range.first).trim()
                if (isAudible(head)) out += Delivery(head, sp, sr, defaultPause(head))
                val d = interjectionDelivery(part.substring(m.range.first, end))
                if (isAudible(d.text)) {
                    out += Delivery(
                        d.text,
                        d.pitch * sp,
                        d.rate * sr,
                        d.pauseAfterMs,
                        fromCue = true,
                    )
                }
                last = end
            }
            val tail = part.substring(last).trim()
            if (isAudible(tail)) out += Delivery(tail, sp, sr, defaultPause(tail))
        }

        var cursor = 0
        for (span in spans) {
            plain(sentence.substring(cursor, span.range.first))
            cursor = span.range.last + 1
            val remark = span.groupValues[1].trim('*').trim()
            val sound = soundOf(remark)
            // `*курсив*` — обычный текст, а не ремарка. Молча выбрасывать слово
            // нельзя: OCR вебтунов и переводов даёт звёздочки сплошь и рядом.
            val starEmphasis = span.value.trimStart().startsWith("*") &&
                sound == null && stateOf(remark) == null && !isInterjection(remark)
            when {
                // Звук произносится сразу, собственным голосом: так вздох
                // отличается от крика, а не читается тем же тоном, что весь
                // текст под ним.
                sound != null -> out += Delivery(
                    sound.spoken,
                    sound.pitch * sp,
                    sound.rate * sr,
                    sound.pauseMs,
                    fromCue = true,
                    isSound = true,
                    soundId = sound.id,
                )
                isInterjection(remark) -> plain(remark)
                // Звёздочки вокруг обычного слова — выделение, а не указание
                // говорящему: произносим само слово.
                starEmphasis -> plain(span.value)
                // Состояние и неизвестная ремарка не произносятся: первое уже
                // учтено множителем, второе не должно читаться как слово.
                else -> Unit
            }
        }
        plain(sentence.substring(cursor))

        if (out.isEmpty()) {
            val clean = render(sentence)
            if (isAudible(clean)) out += Delivery(clean, sp, sr, defaultPause(clean))
        }
        return out
    }

    /**
     * Произносим ли кусок: хотя бы одна буква или цифра. Одинокая пунктуация
     * (`(` или `)` от незакрытой `(*ремарка*)`) не должна уходить в движок
     * отдельным вызовом — он её либо пропустит, либо озвучит как символы.
     */
    internal fun isAudible(text: String): Boolean = text.any { it.isLetterOrDigit() }

    /** Пауза после куска: та же логика, что в движке, но по самому куску. */
    private fun defaultPause(text: String): Int = when {
        text.endsWith("!") || text.endsWith("?") ||
            text.endsWith("‼") || text.endsWith("⁇") -> 420
        text.endsWith(",") || text.endsWith(";") -> 160
        else -> 260
    }
}
